// ─── Fonction d'évaluation ────────────────────────────────────────────────────

/**
 * Évalue la position statiquement.
 * Retourne +∞ si mat des noirs, -∞ si mat des blancs, 0 si nulle.
 */
export function evaluate(chess: Chess): number {
  if (chess.isCheckmate()) {
    // Le joueur dont c'est le trait est mat → l'adversaire gagne
    return chess.turn() === 'w' ? -50_000 : 50_000;
  }
  if (chess.isDraw() || chess.isStalemate()) return 0;

  let score = 0;
  const board = chess.board();

  for (let rank = 0; rank < 8; rank++) {
    for (let file = 0; file < 8; file++) {
      const piece = board[rank][file];
      if (!piece) continue;

      const idx = rank * 8 + file;
      const matVal = PIECE_VALUES[piece.type] ?? 0;
      const table = PIECE_TABLES[piece.type];
      const posBonus = table
        ? (piece.color === 'w' ? table[idx] : table[63 - idx])
        : 0;

      score += piece.color === 'w'
        ? matVal + posBonus
        : -(matVal + posBonus);
    }
  }

  return score;
}
